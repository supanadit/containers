// performance.js — optional delivery optimizations: response compression
// (Brotli + gzip) and browser caching headers (mod_expires).
//
// These are the two levers that make a site *feel* fast on a slow host: fewer
// bytes on the wire and fewer revalidation round-trips. They are deliberately
// off by default, like the security baseline, so existing deployments are
// unaffected and every change is reversible from compose.
//
// Design notes:
//   - All directives are written to container-owned conf/extra/httpd-performance.conf
//     which is fully rewritten on every start. Editing httpd.conf directly is
//     unreliable because the editor verbs append at EOF when a pattern does not
//     match; a dedicated include keeps the config deterministic and idempotent.
//   - Brotli and gzip may both be loaded. Apache's mod_brotli and mod_deflate
//     both inspect Content-Encoding and remove themselves if the content is
//     already encoded, so there is no double compression: the client's
//     Accept-Encoding preference decides which filter runs.
//   - mod_brotli is shipped by the image but is off unless APACHE_BROTLI is set,
//     because it costs more CPU per response than gzip. On a 2-vCPU host that is
//     still a clear win for text, but it is opt-in.
const { editor, fs, log } = require("ezx");
const {
  APACHE_CONF,
  APACHE_PERFORMANCE_CONF,
  WORDPRESS_ROOT,
  IS_COMPRESSION,
  IS_EXPIRES_CACHING,
  APACHE_BROTLI,
  APACHE_BROTLI_QUALITY,
  APACHE_COMPRESS_TYPES,
  APACHE_EXPIRES_ASSETS,
  APACHE_EXPIRES_HTML,
} = require("./env");

// DEFAULT_COMPRESS_TYPES — text-like types that compress well. Images, video
// and archives are already compressed and are excluded (compressing them
// wastes CPU and can make them larger).
const DEFAULT_COMPRESS_TYPES = [
  "text/html",
  "text/plain",
  "text/xml",
  "text/css",
  "text/javascript",
  "text/x-component",
  "application/javascript",
  "application/x-javascript",
  "application/json",
  "application/xml",
  "application/rss+xml",
  "application/atom+xml",
  "application/xhtml+xml",
  "application/ld+json",
  "application/manifest+json",
  "application/vnd.api+json",
  "application/x-font-ttf",
  "font/ttf",
  "font/otf",
  "font/woff",
  "font/woff2",
  "image/svg+xml",
];

// DEFAULT_EXCLUDED — URI suffixes that must never be compressed because they
// are already compressed. Sets the no-gzip / no-brotli env, which both filter
// modules honour.
const DEFAULT_EXCLUDED =
  "\\.(?:gif|jpe?g|png|webp|avif|ico|gz|zip|bz2|rar|7z|mp4|m4v|mov|webm|mp3|ogg|woff2?|pdf)$";

// DEFAULT_EXPIRES_ASSETS — "1 year" for versioned static assets. WordPress
// cache-busts with ?ver= query strings, and the .htaccess rules we generate
// reference filenames, so a long TTL is safe for these.
const DEFAULT_EXPIRES_ASSETS = "access plus 1 year";

// DEFAULT_EXPIRES_HTML — do not let HTML be cached hard: WordPress serves
// dynamic pages and a stale HTML cache causes confusing bugs.
const DEFAULT_EXPIRES_HTML = "access plus 0 seconds";

// splitTypes — the configured list may arrive as a comma/space separated
// string; fall back to the built-in list when empty.
function splitTypes(value) {
  if (!value) return DEFAULT_COMPRESS_TYPES;
  return value
    .split(/[,\s]+/)
    .map((t) => t.trim())
    .filter(Boolean);
}

// performanceEnabled — does any performance directive need to run?
function performanceEnabled() {
  return IS_COMPRESSION || IS_EXPIRES_CACHING;
}

// renderPerformanceConf — build the full include as an ordered line list.
function renderPerformanceConf() {
  const L = [];
  L.push("# httpd-performance.conf — generated by the WordPress container entrypoint.");
  L.push("# This file is fully rewritten on every start. Do not edit by hand.");
  L.push("");

  // -------------------------------------------------------------------------
  // Compression
  // -------------------------------------------------------------------------
  if (IS_COMPRESSION) {
    const types = splitTypes(APACHE_COMPRESS_TYPES);

    L.push("# --- Compression ---------------------------------------------------");
    // The modules are uncommented in httpd.conf (mod_*_module LoadModule lines);
    // only the filter bindings live here.
    L.push("# mod_deflate: gzip fallback for every client.");
    L.push("AddOutputFilterByType DEFLATE " + types.join(" "));

    if (APACHE_BROTLI) {
      L.push("");
      L.push("# mod_brotli: preferred when the client advertises Accept-Encoding: br.");
      L.push("BrotliCompressionQuality " + APACHE_BROTLI_QUALITY);
      L.push("AddOutputFilterByType BROTLI_COMPRESS " + types.join(" "));
      L.push("");
      L.push("# mod_deflate and mod_brotli both register at the same filter priority,");
      L.push("# so whichever is added first wins and the client's preference is NOT");
      L.push("# consulted. Since the deflate filter precedes the brotli filter in the");
      L.push("# chain, gzip would always win. Disable gzip for clients that accept");
      L.push("# brotli so the better encoding is used when it is available.");
      L.push('SetEnvIfNoCase Accept-Encoding "(?:^|[ ,])br(?:$|[ ,;])" no-gzip');
    }

    L.push("");
    L.push("# Never compress content that is already compressed. Both filter");
    L.push("# modules honour these env vars.");
    L.push("SetEnvIfNoCase Request_URI " + DEFAULT_EXCLUDED + " no-gzip dont-vary");
    if (APACHE_BROTLI) {
      L.push("SetEnvIfNoCase Request_URI " + DEFAULT_EXCLUDED + " no-brotli");
    }

    // Ensure intermediates cache the encoded and identity representations
    // separately. mod_brotli/mod_deflate already add Vary: Accept-Encoding, but
    // being explicit here is harmless and covers the deflate-only path. The
    // dont-vary env (set above for already-compressed types) suppresses it.
    L.push("");
    L.push("# Tell caches the response varies by Accept-Encoding.");
    L.push('Header append Vary Accept-Encoding env=!dont-vary');
  }

  // -------------------------------------------------------------------------
  // Browser caching (mod_expires)
  // -------------------------------------------------------------------------
  if (IS_EXPIRES_CACHING) {
    const assets = APACHE_EXPIRES_ASSETS || DEFAULT_EXPIRES_ASSETS;
    const html = APACHE_EXPIRES_HTML || DEFAULT_EXPIRES_HTML;

    L.push("");
    L.push("# --- Browser caching (mod_expires) ----------------------------------");
    L.push("ExpiresActive On");

    // Versioned static assets under wp-content. WordPress appends ?ver=<hash>
    // to enqueued CSS/JS, so a long cache lifetime is safe.
    L.push("ExpiresByType text/css \"" + assets + "\"");
    L.push("ExpiresByType text/javascript \"" + assets + "\"");
    L.push("ExpiresByType application/javascript \"" + assets + "\"");
    L.push("ExpiresByType application/x-javascript \"" + assets + "\"");
    L.push("ExpiresByType image/jpeg \"" + assets + "\"");
    L.push("ExpiresByType image/png \"" + assets + "\"");
    L.push("ExpiresByType image/gif \"" + assets + "\"");
    L.push("ExpiresByType image/webp \"" + assets + "\"");
    L.push("ExpiresByType image/avif \"" + assets + "\"");
    L.push("ExpiresByType image/svg+xml \"" + assets + "\"");
    L.push("ExpiresByType image/x-icon \"" + assets + "\"");
    L.push("ExpiresByType font/woff \"" + assets + "\"");
    L.push("ExpiresByType font/woff2 \"" + assets + "\"");
    L.push("ExpiresByType font/ttf \"" + assets + "\"");
    L.push("ExpiresByType font/otf \"" + assets + "\"");

    // Media — effectively immutable, never cache-busted. Only valid on a site
    // whose uploads are not overwritten in place; the default 1 year is safe
    // for WordPress, which generates new filenames rather than replacing them.
    L.push("ExpiresByType video/mp4 \"" + assets + "\"");

    // HTML and feeds: always revalidate, so dynamic WordPress pages never go
    // stale. This matches the safe default (no Expires header at all) while
    // being explicit.
    L.push("ExpiresByType text/html \"" + html + "\"");
  }

  L.push("");
  return L.join("\n");
}

// modulesNeeded — the modules the active directives require. mod_headers,
// mod_deflate, mod_expires, mod_filter and mod_setenvif are shipped (some
// commented), and mod_brotli only when requested. mod_filter provides
// AddOutputFilterByType and mod_setenvif provides SetEnvIfNoCase; both are
// loaded by the stock config, but enabling them here keeps the include valid
// even if a future base config ships them commented.
function modulesNeeded() {
  const mods = [];
  if (IS_COMPRESSION) {
    mods.push("deflate", "filter", "setenvif", "headers");
    if (APACHE_BROTLI) mods.push("brotli");
  }
  if (IS_EXPIRES_CACHING) mods.push("expires");
  return mods;
}

// enableModule — uncomment the shipped LoadModule line for a module, in place.
// Mirrors security.js/apache.js: the stock httpd.conf ships every module as a
// commented line, so enabling one is a targeted uncomment, not an append.
function enableModule(conf, name) {
  conf.line(
    "^\\s*#?\\s*LoadModule\\s+" + name + "_module\\b",
    "LoadModule " + name + "_module modules/mod_" + name + ".so",
  );
}

// provisionPerformance — write the include file and load its modules, then
// include it from httpd.conf. Runs before provisionHttpdBase so the file exists
// when the Include line is written (provisionHttpdBase appends the security
// include last, so ordering here is preserved).
function provisionPerformance() {
  if (!performanceEnabled()) {
    return;
  }

  const content = renderPerformanceConf();
  fs.write(APACHE_PERFORMANCE_CONF, content, { mode: 0o644 });

  const conf = editor.open(APACHE_CONF);
  for (const mod of modulesNeeded()) {
    enableModule(conf, mod);
  }
  conf.line(
    "^\\s*#?\\s*Include\\s+conf/extra/httpd-performance\\.conf\\s*$",
    "Include conf/extra/httpd-performance.conf",
  );

  const active = [];
  if (IS_COMPRESSION) {
    active.push("compression=" + (APACHE_BROTLI ? "brotli+gzip" : "gzip"));
  }
  if (IS_EXPIRES_CACHING) active.push("expires");
  log.info("Performance tuning enabled: " + active.join(", "));
}

module.exports = {
  performanceEnabled,
  renderPerformanceConf,
  provisionPerformance,
  modulesNeeded,
  enableModule,
  DEFAULT_COMPRESS_TYPES,
  DEFAULT_EXCLUDED,
  DEFAULT_EXPIRES_ASSETS,
  DEFAULT_EXPIRES_HTML,
  enableModule,
};
