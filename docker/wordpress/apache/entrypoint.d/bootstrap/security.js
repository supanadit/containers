// security.js — optional Apache hardening, driven by env.
//
// This is the "opinionated small-server baseline": a set of safe, reversible
// protections that matter most on a small VPS where a single attacker or bot
// flood can take the box down. It complements (and deliberately does not
// duplicate) edge layers such as Anubis, Authelia, CrowdSec or a hosted WAF.
//
// Design note — why a separate include file:
//   All server-scope directives (ServerTokens, TraceEnable, RequestReadTimeout,
//   Header, the uploads <Directory> block, ...) are written to a container-owned
//   conf/extra/httpd-security.conf that is fully reset on every start. Editing
//   httpd.conf directly is unreliable: the editor verbs append at EOF when a
//   pattern does not match, and httpd.conf's tail has already been moved by the
//   php_module block, so a misplaced server-scope directive would be a syntax
//   error. A dedicated file keeps ordering deterministic and idempotent, and a
//   single `Include` line (added by provisionHttpdBase) pulls it in.
//
// Request-scope rules (sensitive files, wp-login) are written into the managed
// sections of the document-root .htaccess, next to the WordPress rewrite rules.
const { editor, fs, log } = require("ezx");
const {
  APACHE_SECURITY_CONF,
  APACHE_CONF,
  WORDPRESS_ROOT,
  WORDPRESS_CONTENT_ROOT,
  IS_HTTPS,
  IS_HIDE_SERVER_INFO,
  IS_DISABLE_DIRLIST,
  IS_DISABLE_TRACE,
  IS_SECURITY_HEADERS,
  IS_BLOCK_SENSITIVE_FILES,
  IS_BLOCK_PHP_IN_UPLOADS,
  IS_SLOWLORIS_PROTECT,
  IS_PROTECT_WPLOGIN,
  IS_HSTS,
  APACHE_REQTIMEOUT,
  APACHE_RATE_LIMIT,
  APACHE_MAX_KEEPALIVE_REQUESTS,
  TRUSTED_PROXY_IPS,
  WP_LOGIN_ALLOW_IPS,
} = require("./env");

// DEFAULT_REQTIMEOUT — mod_reqtimeout settings that blunt Slowloris / slow-body
// attacks without penalising normal clients. Header 20-40s (rate 500 B/s) and
// body 20s (rate 500 B/s) are Apache's own conservative recommendations.
const DEFAULT_REQTIMEOUT = "header=20-40,MinRate=500 body=20,MinRate=500";

// SENSITIVE_PATTERN — files that should never be served. Anchored so it only
// matches the intended names/prefixes. Applied in .htaccess (request scope).
const SENSITIVE_PATTERN =
  "^(\\.env\\..*|\\.git.*|\\.svn.*|wp-config\\.php|readme\\.html|readme\\.txt|license\\.txt|" +
  "xmlrpc\\.php|.*\\.(bak|backup|old|orig|save|swp|sql|log|tar|tgz|zip|gz))$";

// sec — does any hardening directive need to be written at all?
function securityEnabled() {
  return (
    IS_HIDE_SERVER_INFO ||
    IS_DISABLE_DIRLIST ||
    IS_DISABLE_TRACE ||
    IS_SECURITY_HEADERS ||
    IS_BLOCK_SENSITIVE_FILES ||
    IS_BLOCK_PHP_IN_UPLOADS ||
    IS_SLOWLORIS_PROTECT ||
    IS_PROTECT_WPLOGIN ||
    IS_HSTS ||
    !!APACHE_REQTIMEOUT ||
    !!APACHE_RATE_LIMIT ||
    !!APACHE_MAX_KEEPALIVE_REQUESTS ||
    !!TRUSTED_PROXY_IPS
  );
}

// renderSecurityConf — build the full include file as an ordered line list.
function renderSecurityConf() {
  const L = [];
  L.push("# httpd-security.conf — generated by the WordPress container entrypoint.");
  L.push("# This file is fully rewritten on every start. Do not edit by hand.");
  L.push("");

  // Version fingerprinting.
  if (IS_HIDE_SERVER_INFO) {
    L.push("# Hide version/build fingerprinting.");
    L.push("ServerTokens Prod");
    L.push("ServerSignature Off");
  }

  // HTTP method hardening.
  if (IS_DISABLE_TRACE) {
    L.push("# Disable the TRACE method (cross-site tracing).");
    L.push("TraceEnable Off");
  }

  // Keep-alive connection hogging.
  if (APACHE_MAX_KEEPALIVE_REQUESTS) {
    L.push("# Cap requests per keep-alive connection (slowloris-adjacent).");
    L.push("MaxKeepAliveRequests " + APACHE_MAX_KEEPALIVE_REQUESTS);
  }

  // Slowloris / slow-body timeouts.
  if (IS_SLOWLORIS_PROTECT || APACHE_REQTIMEOUT) {
    L.push("# mod_reqtimeout — close connections that send too slowly.");
    L.push("RequestReadTimeout " + (APACHE_REQTIMEOUT || DEFAULT_REQTIMEOUT));
  }

  // Real client IP behind a reverse proxy (e.g. Traefik). Without this every
  // access log line and every IP-based decision sees the proxy address.
  if (TRUSTED_PROXY_IPS) {
    L.push("# Trust X-Forwarded-For from known proxies and restore the real client IP.");
    L.push("RemoteIPHeader X-Forwarded-For");
    for (const cidr of TRUSTED_PROXY_IPS.split(",")) {
      const v = cidr.trim();
      if (v) L.push("RemoteIPTrustedProxy " + v);
    }
  }

  // Security response headers.
  if (IS_SECURITY_HEADERS) {
    L.push("# Security response headers.");
    L.push('Header always set X-Content-Type-Options "nosniff"');
    L.push('Header always set X-Frame-Options "SAMEORIGIN"');
    L.push('Header always set Referrer-Policy "strict-origin-when-cross-origin"');
    L.push('Header always set Permissions-Policy "geolocation=(), microphone=(), camera=()"');
  }
  if (IS_HSTS) {
    L.push("# HSTS — only meaningful over HTTPS; opt-in and easy to get wrong.");
    L.push('Header always set Strict-Transport-Security "max-age=31536000"');
  }
  // Hide the PHP advertising header regardless of IS_HIDE_SERVER_INFO.
  if (IS_SECURITY_HEADERS || IS_HIDE_SERVER_INFO) {
    L.push("Header unset X-Powered-By");
  }

  // Directory listing at the document root. Scoped to the DocumentRoot block so
  // the restrictive defaults of <Directory /> are untouched. `+` adds a flag
  // without resetting what the base config already enabled (FollowSymLinks).
  if (IS_DISABLE_DIRLIST) {
    L.push("# Disable directory listing at the document root.");
    L.push('<Directory "' + WORDPRESS_ROOT + '">');
    L.push("    Options -Indexes");
    L.push("</Directory>");
  }

  // No PHP execution under the uploads directory (defends against an uploaded
  // webshell being executed even if it lands on disk).
  if (IS_BLOCK_PHP_IN_UPLOADS) {
    L.push("# Never execute PHP from the uploads directory.");
    L.push('<Directory "' + WORDPRESS_CONTENT_ROOT + '/uploads">');
    L.push('    <FilesMatch "\\.(php|phtml|phar|php[0-9])$">');
    L.push("        Require all denied");
    L.push("    </FilesMatch>");
    L.push("</Directory>");
  }

  // Bandwidth rate limit (opt-in: can throttle legitimate large downloads).
  if (APACHE_RATE_LIMIT) {
    L.push("# Rate-limit response bandwidth (mod_ratelimit).");
    L.push('<Location "/">');
    L.push("    SetOutputFilter RATE_LIMIT");
    L.push("    SetEnv rate-limit " + APACHE_RATE_LIMIT);
    L.push("</Location>");
  }

  L.push("");
  return L.join("\n");
}

// provisionSecurityBaseline — write the container-owned include file.
function provisionSecurityBaseline() {
  if (!securityEnabled()) {
    return;
  }
  const content = renderSecurityConf();
  fs.write(APACHE_SECURITY_CONF, content, { mode: 0o644 });
  const active = [];
  if (IS_HIDE_SERVER_INFO) active.push("hide-info");
  if (IS_DISABLE_DIRLIST) active.push("no-dirlist");
  if (IS_DISABLE_TRACE) active.push("no-trace");
  if (IS_SECURITY_HEADERS) active.push("headers");
  if (IS_HSTS) active.push("hsts");
  if (IS_BLOCK_PHP_IN_UPLOADS) active.push("no-php-uploads");
  if (IS_SLOWLORIS_PROTECT || APACHE_REQTIMEOUT) active.push("slowloris");
  if (APACHE_RATE_LIMIT) active.push("ratelimit=" + APACHE_RATE_LIMIT);
  if (TRUSTED_PROXY_IPS) active.push("proxy-ip");
  if (APACHE_MAX_KEEPALIVE_REQUESTS) active.push("keepalive=" + APACHE_MAX_KEEPALIVE_REQUESTS);
  log.info("Security baseline enabled: " + active.join(", "));
}

// provisionHtaccessSecurity — request-scope rules written into the managed
// sections of the document-root .htaccess. Kept in its own module so the
// WordPress rewrite section in apache.js stays focused.
function provisionHtaccessSecurity(ed) {
  if (IS_BLOCK_SENSITIVE_FILES) {
    const b = ed.sectionNamed("sensitive", "# BEGIN security-sensitive", "# END security-sensitive");
    b.reset();
    const fm = b.wrap('<FilesMatch "' + SENSITIVE_PATTERN + '">', "</FilesMatch>");
    fm.property("Require", "all denied");
    log.info("Blocking sensitive files (wp-config.php, readme.html, .env, backups, ...)");
  }

  if (IS_PROTECT_WPLOGIN) {
    const b = ed.sectionNamed("wplogin", "# BEGIN security-wplogin", "# END security-wplogin");
    b.reset();
    const loc = b.wrap('<Files "wp-login.php">', "</Files>");
    if (WP_LOGIN_ALLOW_IPS) {
      for (const ip of WP_LOGIN_ALLOW_IPS.split(",")) {
        const v = ip.trim();
        if (v) loc.add("Require ip", v);
      }
      loc.property("Require", "all denied");
      log.info("Restricting wp-login.php to: " + WP_LOGIN_ALLOW_IPS);
    } else {
      // No allowlist: this blocks all direct http(s) access to wp-login.php.
      // Documented as advanced — WordPress logins must then be fronted by a
      // proxy/allowlist, or done via wp-cli.
      loc.property("Require", "all denied");
      log.warn("IS_PROTECT_WPLOGIN=true without WP_LOGIN_ALLOW_IPS — wp-login.php is fully blocked");
    }
  }
}

// enableModule — uncomment the shipped LoadModule line for a module, in place.
// Mirrors apache.js setModule: the stock httpd.conf ships every module as a
// commented line, so enabling one is a targeted uncomment, not an append.
function enableModule(conf, name) {
  conf.line(
    "^\\s*#?\\s*LoadModule\\s+" + name + "_module\\b",
    "LoadModule " + name + "_module modules/mod_" + name + ".so",
  );
}

// requiredModules — the shared modules the active hardening directives need.
// mod_headers, mod_setenvif and mod_reqtimeout are already loaded in the stock
// config; remoteip and ratelimit are not, so they are enabled on demand.
function requiredModules() {
  const mods = [];
  if (TRUSTED_PROXY_IPS) mods.push("remoteip");
  if (APACHE_RATE_LIMIT) mods.push("ratelimit");
  return mods;
}

// apacheSecurityInclude — ensure httpd.conf loads the modules the hardening
// needs and includes the security file. Called from apache.js so the ordering
// stays with the other httpd.conf edits.
function apacheSecurityInclude() {
  if (!securityEnabled()) {
    return;
  }
  const conf = editor.open(APACHE_CONF);
  for (const mod of requiredModules()) {
    enableModule(conf, mod);
  }
  conf.line(
    "^\\s*#?\\s*Include\\s+conf/extra/httpd-[a-z]*security\\.conf\\s*$",
    "Include conf/extra/httpd-security.conf",
  );
}

module.exports = {
  securityEnabled,
  renderSecurityConf,
  provisionSecurityBaseline,
  provisionHtaccessSecurity,
  apacheSecurityInclude,
  enableModule,
  requiredModules,
  DEFAULT_REQTIMEOUT,
  SENSITIVE_PATTERN,
};
