// validation.js — environment validation.
const { fs, log } = require("ezx");
const {
	GRAFANA_TEMPO_CONFIG,
	GRAFANA_TEMPO_DATA_DIR,
	GRAFANA_TEMPO_LISTEN_PORT_HTTP,
	GRAFANA_TEMPO_STORAGE_BACKEND,
} = require("./env");

const KNOWN_TARGETS = [
	"all",
	"distributor",
	"ingester",
	"compactor",
	"querier",
	"query-frontend",
	"query-scheduler",
	"scalable-single-binary",
];

// commandExists — resolve a binary on PATH without a shell.
function commandExists(name) {
	return fs.which(name);
}

// validateEnvironment — run every check and report the outcome.
function validateEnvironment() {
	if (!commandExists("tempo")) {
		log.error("Missing dependency: tempo");
		return false;
	}

	const port = parseInt(String(GRAFANA_TEMPO_LISTEN_PORT_HTTP), 10);
	if (!Number.isInteger(port) || port < 1 || port > 65535) {
		log.error("GRAFANA_TEMPO_LISTEN_PORT_HTTP is not a valid port: " + GRAFANA_TEMPO_LISTEN_PORT_HTTP);
		return false;
	}

	if (!["local", "s3"].includes(GRAFANA_TEMPO_STORAGE_BACKEND)) {
		log.error("Invalid GRAFANA_TEMPO_STORAGE_BACKEND: " + GRAFANA_TEMPO_STORAGE_BACKEND + " (must be local or s3)");
		return false;
	}

	if (!KNOWN_TARGETS.includes(String(envStr("GRAFANA_TEMPO_TARGET", "scalable-single-binary")))) {
		log.error("Unknown GRAFANA_TEMPO_TARGET: " + envStr("GRAFANA_TEMPO_TARGET", ""));
		return false;
	}

	if (!fs.exists(GRAFANA_TEMPO_DATA_DIR)) {
		log.error("GRAFANA_TEMPO_DATA_DIR does not exist: " + GRAFANA_TEMPO_DATA_DIR);
		return false;
	}
	// The config is generated by config.js before this runs.
	if (!fs.exists(GRAFANA_TEMPO_CONFIG)) {
		log.error("Tempo configuration file not found at " + GRAFANA_TEMPO_CONFIG);
		return false;
	}
	return true;
}

// envStr — small helper so validation does not need to re-import every name.
function envStr(name, def) {
	const { env } = require("ezx");
	return env.get(name, def);
}

module.exports = {
	validateEnvironment,
	commandExists,
	KNOWN_TARGETS,
};
