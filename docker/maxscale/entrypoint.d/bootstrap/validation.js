// validation.js — environment validation.
const { fs, log } = require("ezx");
const {
	MAXSCALE_CONFIG_FILE,
	MAXSCALE_SERVICE_READWRITE_ROUTES,
	MAXSCALE_PORT,
	MAXSCALE_REST_PORT,
} = require("./env");

// commandExists — resolve a binary on PATH without a shell.
function commandExists(name) {
	return fs.which(name);
}

// validateEnvironment — run every check and report the outcome.
function validateEnvironment() {
	for (const cmd of ["maxscale", "maxctrl"]) {
		if (!commandExists(cmd)) {
			log.error("Missing dependency: " + cmd);
			return false;
		}
	}
	for (const [name, value] of [
		["MAXSCALE_PORT", MAXSCALE_PORT],
		["MAXSCALE_REST_PORT", MAXSCALE_REST_PORT],
	]) {
		const port = parseInt(String(value), 10);
		if (!Number.isInteger(port) || port < 1 || port > 65535) {
			log.error(name + " is not a valid port: " + value);
			return false;
		}
	}
	if (!MAXSCALE_SERVICE_READWRITE_ROUTES) {
		log.error("MAXSCALE_SERVICE_READWRITE_ROUTES must not be empty");
		return false;
	}
	// The config is generated by config.js before this runs.
	if (!fs.exists(MAXSCALE_CONFIG_FILE)) {
		log.error("MaxScale configuration file not found at " + MAXSCALE_CONFIG_FILE);
		return false;
	}
	return true;
}

module.exports = {
	validateEnvironment,
	commandExists,
};
