// validation.js — environment validation.
const { fs, log } = require("ezx");
const {
	GRAFANA_LOKI_CONFIG,
	GRAFANA_LOKI_DATA_DIR,
	GRAFANA_LOKI_LISTEN_PORT_HTTP,
	GRAFANA_LOKI_LISTEN_PORT_GRPC,
	GRAFANA_LOKI_STORAGE_BACKEND,
	GRAFANA_LOKI_TARGET,
} = require("./env");

const KNOWN_TARGETS = ["", "all", "read", "write", "backend"];

// commandExists — resolve a binary on PATH without a shell.
function commandExists(name) {
	return fs.which(name);
}

// validateEnvironment — run every check and report the outcome.
function validateEnvironment() {
	const checks = [["loki", commandExists("loki")]];
	for (const [name, passed] of checks) {
		if (!passed) {
			log.error("Missing dependency: " + name);
			return false;
		}
	}

	for (const [name, value] of [
		["GRAFANA_LOKI_LISTEN_PORT_HTTP", GRAFANA_LOKI_LISTEN_PORT_HTTP],
		["GRAFANA_LOKI_LISTEN_PORT_GRPC", GRAFANA_LOKI_LISTEN_PORT_GRPC],
	]) {
		const port = parseInt(String(value), 10);
		if (!Number.isInteger(port) || port < 1 || port > 65535) {
			log.error(name + " is not a valid port: " + value);
			return false;
		}
	}

	if (!["filesystem", "s3"].includes(GRAFANA_LOKI_STORAGE_BACKEND)) {
		log.error("Invalid GRAFANA_LOKI_STORAGE_BACKEND: " + GRAFANA_LOKI_STORAGE_BACKEND + " (must be filesystem or s3)");
		return false;
	}

	if (!KNOWN_TARGETS.includes(GRAFANA_LOKI_TARGET)) {
		log.error("Unknown GRAFANA_LOKI_TARGET: " + GRAFANA_LOKI_TARGET);
		log.error("Available targets: read, write, backend (empty = all)");
		return false;
	}

	// The config is generated by config.js before this runs.
	if (!fs.exists(GRAFANA_LOKI_CONFIG)) {
		log.error("Loki configuration file not found at " + GRAFANA_LOKI_CONFIG);
		return false;
	}
	// The data directory must exist for the filesystem backend.
	if (!fs.exists(GRAFANA_LOKI_DATA_DIR)) {
		log.error("GRAFANA_LOKI_DATA_DIR does not exist: " + GRAFANA_LOKI_DATA_DIR);
		return false;
	}
	return true;
}

module.exports = {
	validateEnvironment,
	commandExists,
	KNOWN_TARGETS,
};
