// validation.js — environment validation.
const { fs, log } = require("ezx");
const {
	GRAFANA_MIMIR_CONFIG,
	GRAFANA_MIMIR_DATA_DIR,
	MIMIR_BIN,
	MIMIR_HTTP_PORT,
	MIMIR_TSDB_DIR,
	MIMIR_INGESTER_REPLICATION_FACTOR,
} = require("./env");

// commandExists — resolve a binary on PATH without a shell.
function commandExists(name) {
	return fs.which(name);
}

// validateEnvironment — run every check and report the outcome.
function validateEnvironment() {
	// The bash entrypoint exited 1 when the configured binary was not
	// executable; keep that check.
	if (!fs.exists(MIMIR_BIN)) {
		log.error("Unable to locate executable at " + MIMIR_BIN);
		return false;
	}

	const port = parseInt(String(MIMIR_HTTP_PORT), 10);
	if (!Number.isInteger(port) || port < 1 || port > 65535) {
		log.error("MIMIR_HTTP_PORT is not a valid port: " + MIMIR_HTTP_PORT);
		return false;
	}

	if (MIMIR_INGESTER_REPLICATION_FACTOR < 1) {
		log.error("MIMIR_INGESTER_REPLICATION_FACTOR must be >= 1: " + MIMIR_INGESTER_REPLICATION_FACTOR);
		return false;
	}

	if (!fs.exists(MIMIR_TSDB_DIR)) {
		log.error("MIMIR_TSDB_DIR does not exist: " + MIMIR_TSDB_DIR);
		return false;
	}
	// The config is generated by config.js before this runs.
	if (!fs.exists(GRAFANA_MIMIR_CONFIG)) {
		log.error("Mimir configuration file not found at " + GRAFANA_MIMIR_CONFIG);
		return false;
	}
	return true;
}

module.exports = {
	validateEnvironment,
	commandExists,
};
