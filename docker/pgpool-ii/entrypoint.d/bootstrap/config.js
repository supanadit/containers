// OWNER — "user:group" for every file the container writes.
const OWNER = PGPOOL_USER + ":" + PGPOOL_GROUP;

// parseBackends — split "host:port,host:port" with optional parallel weight and
// flag lists. Mirrors the bash parse_backends (default flag DISALLOW_TO_FAILOVER,
// default weight 1).
function parseBackends() {
  const hosts = (PGPOOL_BACKENDS || "")
    .split(",")
    .map((s) => s.trim())
    .filter(Boolean);
  const weights = PGPOOL_BACKEND_WEIGHTS
    ? PGPOOL_BACKEND_WEIGHTS.split(",").map((s) => s.trim())
    : [];
  const flags = PGPOOL_BACKEND_FLAGS
    ? PGPOOL_BACKEND_FLAGS.split(",").map((s) => s.trim())
    : [];

  return hosts.map((entry, i) => {
    const idx = entry.lastIndexOf(":");
    const host = idx >= 0 ? entry.slice(0, idx) : entry;
    const port = idx >= 0 ? entry.slice(idx + 1) : "5432";
    return {
      host,
      port,
      weight: weights[i] || "1",
      flag: flags[i] || "DISALLOW_TO_FAILOVER",
    };
  });
}

// pgpoolConf — the explicit base document (parity with the bash heredoc).
function pgpoolConf() {
  const b = config.builder({ separator: " = " });

  b.comment("pgpool-II configuration generated by container entrypoint");

  b.comment("Connection settings");
  b.set("listen_addresses", "'*'");
  b.set("port", PGPOOL_PORT);
  // pgpool's compiled-in default is /var/run/pgpool/pgpool.pid, which does not
  // exist in this image and makes pgpool abort at startup with
  // 'could not open pid file'. Point it at the volume-normalized run dir.
  b.set("pid_file_name", "'" + PGPOOL_PID_FILE + "'");
  b.set("pcp_listen_addresses", "'*'");
  b.set("pcp_port", PGPOOL_PCP_PORT);
  b.set("pcp_timeout", PGPOOL_PCP_TIMEOUT);

  b.comment("Pool settings");
  b.set("num_init_children", PGPOOL_NUM_INIT_CHILDREN);
  b.set("max_pool", PGPOOL_MAX_POOL);
  b.set("child_life_time", PGPOOL_CHILD_LIFE_TIME);
  b.set("connection_life_time", PGPOOL_CONNECTION_LIFE_TIME);
  b.set("child_max_connections", PGPOOL_CHILD_MAX_CONNECTIONS);

  b.comment("Load balancing");
  b.set("load_balance_mode", PGPOOL_LOAD_BALANCE_MODE);
  b.set("ignore_leading_white_space", PGPOOL_IGNORE_LEADING_WHITE_SPACE);

  b.comment("Master slave mode");
  b.set("master_slave_mode", PGPOOL_MASTER_SLAVE_MODE);
  b.set("master_slave_sub_mode", "'" + PGPOOL_MASTER_SLAVE_SUB_MODE + "'");

  b.comment("Query routing and validation");
  b.set("enable_hint_query", PGPOOL_ENABLE_HINT_QUERY);
  b.set("validate_query", PGPOOL_VALIDATE_QUERY);
  b.set("replication_check", PGPOOL_REPLICATION_CHECK);

  // Native pgpool hooks — pass-through only. The container never authors a
  // callback script; users supply a path via PGPOOL_FAILOVER_COMMAND /
  // PGPOOL_FOLLOW_MASTER_SCRIPT.
  if (PGPOOL_FOLLOW_MASTER_SCRIPT) {
    b.set("follow_master_command", "'" + PGPOOL_FOLLOW_MASTER_SCRIPT + "'");
  }

  if (PGPOOL_MEMORY_CACHE_MODE) {
    b.comment("Memory Cache (Query Cache)");
    b.set("memory_cache_mode", "on");
    b.set("memqcache_cache_blocks", PGPOOL_MEMQCACHE_CACHE_BLOCKS);
    b.set("memqcache_block_size", PGPOOL_MEMQCACHE_BLOCK_SIZE);
    b.set("memqcache_maxcache", PGPOOL_MEMQCACHE_MAXCACHE);
    b.set("memqcache_expire_time", PGPOOL_MEMQCACHE_EXPIRE_TIME);
    b.set("memqcache_total_size", PGPOOL_MEMQCACHE_TOTAL_SIZE);
  }

  b.comment("Connection pooling");
  b.set("connection_cache", PGPOOL_CONNECTION_CACHE);
  b.set("reset_query_list", "'" + PGPOOL_RESET_QUERY_LIST + "'");
  b.set("auto_db_remove", PGPOOL_AUTO_DB_REMOVE);
  b.set("autoicache_remove", PGPOOL_AUTOICACHE_REMOVE);

  b.comment("Authentication");
  b.set("enable_pool_hba", PGPOOL_ENABLE_POOL_HBA ? "on" : "off");
  b.set("pool_passwd", "'" + PGPOOL_POOL_PASSWD + "'");

  b.comment("Health check");
  b.set("health_check_timeout", PGPOOL_HEALTH_CHECK_TIMEOUT);
  b.set("health_check_period", PGPOOL_HEALTH_CHECK_PERIOD);
  b.set("health_check_user", "'" + PGPOOL_HEALTH_CHECK_USER + "'");
  b.set("health_check_password", "'" + PGPOOL_HEALTH_CHECK_PASSWORD + "'");
  b.set("health_check_database", "'" + PGPOOL_HEALTH_CHECK_DATABASE + "'");
  b.set("health_check_max_retries", PGPOOL_HEALTH_CHECK_MAX_RETRIES);
  b.set("health_check_retry_delay", PGPOOL_HEALTH_CHECK_RETRY_DELAY);

  b.comment("Connection timeout");
  b.set("connect_timeout", PGPOOL_CONNECT_TIMEOUT);

  b.comment("Streaming replication check");
  b.set("sr_check_period", PGPOOL_SR_CHECK_PERIOD);
  b.set("sr_check_user", "'" + PGPOOL_SR_CHECK_USER + "'");
  b.set("sr_check_password", "'" + PGPOOL_SR_CHECK_PASSWORD + "'");
  b.set("sr_check_database", "'" + PGPOOL_SR_CHECK_DATABASE + "'");
  b.set("delay_threshold", PGPOOL_DELAY_THRESHOLD);
  b.set("delay_threshold_by_time", PGPOOL_DELAY_THRESHOLD_BY_TIME);
  b.set("prefer_lower_delay_standby", PGPOOL_PREFER_LOWER_DELAY_STANDBY);
  b.set("log_standby_delay", "'" + PGPOOL_LOG_STANDBY_DELAY + "'");

  b.comment("Primary node detection");
  b.set("search_primary_node_timeout", PGPOOL_SEARCH_PRIMARY_NODE_TIMEOUT);

  b.comment("SSL/TLS Configuration");
  b.set("ssl", PGPOOL_SSL ? "on" : "off");
  if (PGPOOL_SSL) {
    if (PGPOOL_SSL_KEY) b.set("ssl_key", "'" + PGPOOL_SSL_KEY + "'");
    if (PGPOOL_SSL_CERT) b.set("ssl_cert", "'" + PGPOOL_SSL_CERT + "'");
    if (PGPOOL_SSL_SECURITY_MODE) b.set("ssl_security_mode", "'" + PGPOOL_SSL_SECURITY_MODE + "'");
  }

  if (PGPOOL_ENABLE_WATCHDOG) {
    b.comment("Watchdog (High Availability)");
    b.set("use_watchdog", "on");
    b.set("wd_hostname", "'" + PGPOOL_WD_HOSTNAME + "'");
    b.set("wd_port", PGPOOL_WD_PORT);
    b.set("delegate_IP", "'" + PGPOOL_DELEGATE_IP + "'");
    b.set("wd_lifecheck_method", "'" + PGPOOL_WD_LIFECHECK_METHOD + "'");
    b.set("wd_interval", PGPOOL_WD_INTERVAL);
    b.set("wd_priority", PGPOOL_WD_PRIORITY);
    b.set("wd_failover_timeout", PGPOOL_WD_FAILOVER_TIMEOUT);
    if (PGPOOL_WD_AUTHENTICATION) b.set("wd_authentication", "'" + PGPOOL_WD_AUTHENTICATION + "'");
  }

  b.comment("Logging");
  b.set("log_destination", "'stderr'");
  b.set("log_line_prefix", "'%t: pid %p: '");
  b.set("log_connections", "on");
  b.set("log_hostname", PGPOOL_LOG_HOSTNAME);
  b.set("log_statement", "off");

  b.comment("Error reporting");
  b.set("log_error_verbosity", "default");
  b.set("client_min_messages", "notice");
  b.set("log_min_messages", PGPOOL_LOG_MIN_MESSAGES);

  if (PGPOOL_FAILOVER_COMMAND) {
    b.set("failover_command", "'" + PGPOOL_FAILOVER_COMMAND + "'");
  }

  // Native backend_N keys.
  parseBackends().forEach((be, i) => {
    b.comment("Backend " + i);
    b.set("backend_hostname" + i, "'" + be.host + "'");
    b.set("backend_port" + i, be.port);
    b.set("backend_weight" + i, be.weight);
    b.set("backend_data_directory" + i, "''");
    b.set("backend_flag" + i, "'" + be.flag + "'");
    b.set("backend_application_name" + i, "'server" + i + "'");
  });

  return b.build();
}

// poolHbaConf — default authentication rules (the bash generate_pool_hba_config
// heredoc), plus any PGPOOL_HBA_ADD_<N> lines the user supplied.
function poolHbaConf() {
  const base = config.build({
    comment: "pool_hba.conf configuration generated by container entrypoint",
    rows: [
      ["local", "all", "all", "trust"],
      ["host", "all", "all", "0.0.0.0/0", "md5"],
      ["host", "all", "all", "::/0", "md5"],
    ],
  });
  const extra = envLines("^PGPOOL_HBA_ADD_([0-9]+)$")
    .sort((a, b) => a.name.localeCompare(b.name, undefined, { numeric: true }))
    .map((e) => e.value)
    .filter(Boolean);
  return extra.length ? base + extra.join("\n") + "\n" : base;
}

// envLines — collect { name, value } entries whose name matches a pattern.
// Replaces the bash `env | grep` loops.
function envLines(pattern) {
  const re = new RegExp(pattern);
  const out = [];
  const all = env.all();
  for (const name of Object.keys(all)) {
    if (!re.test(name)) continue;
    out.push({ name, value: all[name] });
  }
  return out;
}

// applyConfigOverrides — apply PGPOOL_CONFIG_<KEY> env overrides onto the
// generated pgpool.conf. An existing "key =" line is replaced in place; an
// unknown key is appended. This mirrors the declarative set-property op without
// needing file provisioning, because generatePoolPasswd() must run after this
// file exists on disk.
function applyConfigOverrides(text) {
  const overrides = envLines("^PGPOOL_CONFIG_(.+)$");
  if (!overrides.length) return text;

  const lines = text.split("\n");
  for (const { name, value } of overrides) {
    const key = name.slice("PGPOOL_CONFIG_".length).toLowerCase();
    const re = new RegExp("^" + key + "\\s*=");
    const rendered = key + " = " + formatValue(value);
    const idx = lines.findIndex((l) => re.test(l));
    if (idx >= 0) {
      lines[idx] = rendered;
    } else {
      lines.push(rendered);
    }
  }
  return lines.join("\n");
}

// formatValue — quote a value unless it is a bare number or an on/off-style
// keyword (the bash emitted numbers and on/off unquoted).
function formatValue(value) {
  const v = String(value).trim();
  if (/^(?:[0-9]+(?:\.[0-9]+)?(?:kB|MB|GB|TB|ms|s|min|h|d)?|on|off|true|false)$/.test(v)) {
    return v;
  }
  return "'" + v.replace(/'/g, "''") + "'";
}

// ensurePoolKey — make sure an AES key exists at PGPOOL_KEY_PATH and return it.
//
// pgpool reads the key itself to decrypt pool_passwd entries at startup; pg_enc
// reads the same file to encrypt them. The operator can supply PGPOOL_KEY (the
// key literally) or PGPOOL_KEY_FILE (a path); otherwise a 32-byte key is
// generated once and reused, so an existing volume keeps decrypting after a
// restart.
//
// The key is written to TWO places: PGPOOL_KEY_PATH (the canonical copy pg_enc
// is pointed at) and PGPOOL_KEY_HOME_PATH, which is postgres's $HOME/.pgpoolkey.
// pgpool resolves the key from $PGPOOLKEYFILE or, failing that, <home>/.pgpoolkey
// — and the env var does not reliably survive to the pgpool process here (it
// silently fell back to <home>/.pgpoolkey and answered every query with
// "unable to decrypt password from pool_passwd"). Writing the home copy makes
// pgpool find it whether or not the env var took effect. The two files are kept
// byte-identical so a stale copy can never cause a decrypt failure.
function writePoolKey(key) {
  for (const path of [PGPOOL_KEY_PATH, PGPOOL_KEY_HOME_PATH]) {
    if (!path) {
      continue;
    }
    fs.write(path, key + "\n", { mode: 0o600, owner: OWNER });
    fs.chmod(path, 0o600);
    fs.chown(path, OWNER);
  }
}

function ensurePoolKey() {
  if (PGPOOL_KEY) {
    writePoolKey(PGPOOL_KEY);
    return PGPOOL_KEY;
  }

  if (fs.exists(PGPOOL_KEY_PATH)) {
    // Reuse the existing key so an existing volume keeps decrypting after a
    // restart; regenerate only if it is empty/unreadable.
    let existing = "";
    try {
      existing = (editor.open(PGPOOL_KEY_PATH).read() || "").trim();
    } catch (e) {
      log.warn("could not read pool key " + PGPOOL_KEY_PATH + ": " + e);
    }
    if (existing) {
      writePoolKey(existing);
      return existing;
    }
  }

  // 32 random bytes, hex-encoded (64 chars) — comfortably past AES's minimum.
  const key = crypto.randomHex(32);
  writePoolKey(key);
  log.info("Generated pool key at " + PGPOOL_KEY_PATH);
  return key;
}

// generatePoolPasswd — create pool_passwd with pgpool's own pg_enc tool (no
// shell, no reimplemented crypto).
//
// This MUST use pg_enc (AES), not pg_md5. A backend whose password is stored as
// scram-sha-256 — the PostgreSQL default since v14 — cannot be authenticated to
// with an md5, plaintext, or SCRAM-verifier pool_passwd entry: for SCRAM, pgpool
// has to compute a client proof, which needs the recoverable password. Only an
// AES entry (decryptable via the pool key) provides it. See pgpool's
// get_pgpool_config_user_password(): anything that is not PLAINTEXT or MD5 is
// treated as unusable for this purpose.
//
// Notes, each learned the hard way:
//  1. pg_enc MUST be told which pgpool.conf to read (-f), otherwise it reads its
//     compiled-in default and exits with "Unable to get configuration". It reads
//     pgpool.conf to locate pool_passwd, so this runs after that file is written.
//  2. pg_enc -m writes the pool_passwd entry itself; its stdout is progress
//     chatter. The caller must NOT overwrite the file with stdout.
//  3. The password goes through a 0600 input file (-i), and the key through either
//     --key-file (a path) or PGPOOLKEYFILE, never argv — so neither secret shows
//     up in the process list.
//  4. AES support is a build-time feature (--with-openssl). If pg_enc reports
//     "AES encryption is not supported by this build", the image was built
//     without it and pool_passwd cannot hold a usable backend password.
function generatePoolPasswd() {
  if (!PGPOOL_BACKEND_PASSWORD) {
    log.warn("PGPOOL_BACKEND_PASSWORD not set, skipping pool_passwd generation");
    return false;
  }

  ensurePoolKey();

  const input = PGPOOL_RUN_DIR + "/pg_enc.input";
  fs.write(input, PGPOOL_HEALTH_CHECK_USER + ":" + PGPOOL_BACKEND_PASSWORD + "\n", {
    mode: 0o600,
    owner: OWNER,
  });
  fs.chmod(input, 0o600);

  let res;
  try {
    res = process.capture({
      process: {
        binaryPath: "pg_enc",
        arguments: ["-m", "-f", PGPOOL_CONF, "-k", PGPOOL_KEY_PATH, "-i", input],
      },
    });
  } finally {
    if (fs.exists(input)) fs.remove(input);
  }

  if (res.code !== 0) {
    // Surface the classic build-time cause instead of a bare non-zero exit.
    if (/AES encryption is not supported/i.test(res.stderr || "")) {
      log.error(
        "pg_enc reports AES is unsupported by this pgpool build; it must be " +
          "compiled with --with-openssl for pool_passwd to authenticate against " +
          "scram-sha-256 backends"
      );
    }
    log.error("pg_enc failed (code=" + res.code + "): " + res.stderr);
    return false;
  }

  // pg_enc has already written pool_passwd; only fix ownership/mode.
  fs.chmod(POOL_PASSWD_FILE, 0o600);
  fs.chown(POOL_PASSWD_FILE, OWNER);
  return true;
}

// provisionConfig — write pgpool.conf, then pool_hba.conf, then pool_passwd
// (which needs pgpool.conf on disk). Called from main() before chain.run so the
// files exist by the time pgpool starts, exactly like the bash entrypoint.
function provisionConfig() {
  fs.write(PGPOOL_CONF, applyConfigOverrides(pgpoolConf()), { mode: 0o640, owner: OWNER });
  fs.chmod(PGPOOL_CONF, 0o640);
  fs.chown(PGPOOL_CONF, OWNER);

  if (PGPOOL_ENABLE_POOL_HBA) {
    fs.write(POOL_HBA_CONF, poolHbaConf(), { mode: 0o640, owner: OWNER });
    fs.chmod(POOL_HBA_CONF, 0o640);
    fs.chown(POOL_HBA_CONF, OWNER);
  } else {
    // pgpool still reads pool_hba.conf when enable_pool_hba is off only if it
    // exists; removing a stale copy keeps the previous container's behaviour
    // (which only wrote it when enabled).
    if (fs.exists(POOL_HBA_CONF)) fs.remove(POOL_HBA_CONF);
  }

  return generatePoolPasswd();
}

